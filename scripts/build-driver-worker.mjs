import ts from "typescript";
import { readFileSync, writeFileSync } from "node:fs";
// The shared engine has only type imports. Compile it with the existing pinned
// TypeScript toolchain; fail if a runtime dependency is introduced accidentally.
const output = ts.transpileModule(
  readFileSync("apps/web/src/lib/offline.ts", "utf8"),
  {
    compilerOptions: {
      target: ts.ScriptTarget.ES2022,
      module: ts.ModuleKind.CommonJS,
    },
  },
).outputText;
if (/require\(/.test(output))
  throw new Error("Worker engine must remain dependency-free");
writeFileSync(
  "apps/web/public/driver-sync.js",
  `/* Generated by build-driver-worker.mjs. */\n/* eslint-disable -- generated from typechecked offline.ts */\nvar FleetPilotSync=(()=>{const exports={};\n${output}\nreturn exports;})();\n`,
);
